CREATE TABLE STG_WEATHER (
    CITY VARCHAR(100),
    WEATHER_DATE DATE,
    TEMPERATURE FLOAT,
    PRECIPITATION FLOAT,
    MAX_WIND_SPEED FLOAT
);

CREATE TABLE WEATHER_DW.WEATHER.DIM_DATE (
    DATE_KEY INT PRIMARY KEY,
    FULL_DATE DATE NOT NULL UNIQUE,
    YEAR INT,
    MONTH INT,
    MONTH_NAME VARCHAR(20),
    DAY INT
);

INSERT INTO WEATHER_DW.WEATHER.DIM_DATE
    (DATE_KEY, FULL_DATE, YEAR, MONTH, MONTH_NAME, DAY)
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(WEATHER_DATE, 'YYYYMMDD')) AS DATE_KEY,
    WEATHER_DATE AS FULL_DATE,
    YEAR(WEATHER_DATE) AS YEAR,
    MONTH(WEATHER_DATE) AS MONTH,
    MONTHNAME(WEATHER_DATE) AS MONTH_NAME,
    DAY(WEATHER_DATE) AS DAY
FROM WEATHER_DW.WEATHER.STG_WEATHER
WHERE WEATHER_DATE IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM WEATHER_DW.WEATHER.DIM_DATE d
      WHERE d.FULL_DATE = STG_WEATHER.WEATHER_DATE
  );

  CREATE TABLE WEATHER_DW.WEATHER.DIM_LOCATION (
    LOCATION_KEY INT AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    CITY VARCHAR(100) NOT NULL UNIQUE,
    LATITUDE FLOAT,
    LONGITUDE FLOAT
);
