CREATE TABLE WEATHER_DW.WEATHER.FACT_WEATHER (
    WEATHER_FACT_KEY INT AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    DATE_KEY INT NOT NULL,
    LOCATION_KEY INT NOT NULL,
    TEMPERATURE FLOAT,
    PRECIPITATION FLOAT,
    MAX_WIND_SPEED FLOAT,

    CONSTRAINT FK_FACT_DATE
        FOREIGN KEY (DATE_KEY)
        REFERENCES WEATHER_DW.WEATHER.DIM_DATE(DATE_KEY),

    CONSTRAINT FK_FACT_LOCATION
        FOREIGN KEY (LOCATION_KEY)
        REFERENCES WEATHER_DW.WEATHER.DIM_LOCATION(LOCATION_KEY),

    CONSTRAINT UQ_WEATHER_DATE_LOCATION
        UNIQUE (DATE_KEY, LOCATION_KEY)
);

INSERT INTO WEATHER_DW.WEATHER.FACT_WEATHER (
    DATE_KEY,
    LOCATION_KEY,
    TEMPERATURE,
    PRECIPITATION,
    MAX_WIND_SPEED
)

SELECT
    d.DATE_KEY,
    l.LOCATION_KEY,
    s.TEMPERATURE,
    s.PRECIPITATION,
    s.MAX_WIND_SPEED
FROM WEATHER_DW.WEATHER.STG_WEATHER s
JOIN WEATHER_DW.WEATHER.DIM_DATE d
    ON s.WEATHER_DATE = d.FULL_DATE
JOIN WEATHER_DW.WEATHER.DIM_LOCATION l
    ON s.CITY = l.CITY
WHERE NOT EXISTS (
    SELECT 1
    FROM WEATHER_DW.WEATHER.FACT_WEATHER f
    WHERE f.DATE_KEY = d.DATE_KEY
      AND f.LOCATION_KEY = l.LOCATION_KEY
);

