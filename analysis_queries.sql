-- 1. Average temperature by city
SELECT
    l.CITY,
    AVG(f.TEMPERATURE) AS AVG_TEMPERATURE
FROM WEATHER_DW.WEATHER.FACT_WEATHER f
JOIN WEATHER_DW.WEATHER.DIM_LOCATION l
    ON f.LOCATION_KEY = l.LOCATION_KEY
GROUP BY l.CITY
ORDER BY AVG_TEMPERATURE DESC;


-- 2. Total precipitation by city
SELECT
    l.CITY,
    SUM(f.PRECIPITATION) AS TOTAL_PRECIPITATION
FROM WEATHER_DW.WEATHER.FACT_WEATHER f
JOIN WEATHER_DW.WEATHER.DIM_LOCATION l
    ON f.LOCATION_KEY = l.LOCATION_KEY
GROUP BY l.CITY
ORDER BY TOTAL_PRECIPITATION DESC;


-- 3. Maximum wind speed by city
SELECT
    l.CITY,
    MAX(f.MAX_WIND_SPEED) AS MAX_WIND_SPEED
FROM WEATHER_DW.WEATHER.FACT_WEATHER f
JOIN WEATHER_DW.WEATHER.DIM_LOCATION l
    ON f.LOCATION_KEY = l.LOCATION_KEY
GROUP BY l.CITY
ORDER BY MAX_WIND_SPEED DESC;


-- 4. Daily weather summary across all cities
SELECT
    d.FULL_DATE,
    AVG(f.TEMPERATURE) AS AVG_TEMPERATURE,
    SUM(f.PRECIPITATION) AS TOTAL_PRECIPITATION,
    MAX(f.MAX_WIND_SPEED) AS MAX_WIND_SPEED
FROM WEATHER_DW.WEATHER.FACT_WEATHER f
JOIN WEATHER_DW.WEATHER.DIM_DATE d
    ON f.DATE_KEY = d.DATE_KEY
GROUP BY d.FULL_DATE
ORDER BY d.FULL_DATE;